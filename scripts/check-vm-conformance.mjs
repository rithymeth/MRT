#!/usr/bin/env node
// Checks the Rust bytecode VM (compiler/crates/mrt-interp/src/vm) against the
// Python reference implementation over the shared conformance corpus in
// scripts/parity-cases.mjs -- the same corpus the other three implementations
// are held to.
//
// A construct the VM cannot compile is recorded as *unsupported* rather than
// as a mismatch. That is a hole big enough to hide a regression in, so the
// unsupported set is a ratchet: the harness fails both when a case newly
// stops compiling and when a listed case starts working. Widening the
// compiler is therefore expected to fail this script once, on purpose, until
// the list is shortened.
//
// That list is now empty. The VM compiles the whole language -- the same
// point the tree-walker reached -- which is exactly when the ratchet starts
// earning its keep: from here there is nowhere for a regression to hide as
// "not implemented yet".
//
// What matters here is the other number: of the cases the VM *does* compile,
// every one must match the reference byte for byte. A VM that runs less of
// the language is a work in progress; a VM that runs it differently is a bug.
//
// Run with `npm run check:vm`.

import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, mkdtempSync, writeFileSync, mkdirSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { REGRESSION_CASES, MODULE_CASES, ENGINE_SPECIFIC_EXAMPLES } from './parity-cases.mjs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(__dirname, '..')

// Cases the VM cannot compile yet. Generated by running this harness; keep it
// sorted so the diff when the compiler widens is readable.
const UNSUPPORTED = new Set(JSON.parse(
  readFileSync(path.join(__dirname, 'vm-unsupported.json'), 'utf8'),
))

// The compiler's own refusal text, which is how an unsupported program is
// told apart from a wrong answer.
const NOT_IMPLEMENTED = /is not compiled by the VM yet/

function run(cmd, args, options = {}) {
  try {
    const stdout = execFileSync(cmd, args, {
      cwd: repoRoot,
      encoding: 'utf8',
      stdio: ['pipe', 'pipe', 'pipe'],
      ...options,
    })
    return stdout.trimEnd()
  } catch (err) {
    // A program that stops on an error exits non-zero and writes the message
    // to stderr. That text is part of the language's behaviour, so both sides
    // are compared on stdout+stderr rather than only on success.
    if (err.stdout === undefined && err.stderr === undefined) throw err
    return `${err.stdout ?? ''}${err.stderr ?? ''}`.trimEnd()
  }
}

const binary = path.join(repoRoot, 'compiler/target/release/mrt-run')

function runPythonFile(file) {
  return run('python3', ['-m', 'mrt', file])
}

function runVmFile(file) {
  return run(binary, ['--vm', file])
}

function main() {
  process.stderr.write('building mrt-run...\n')
  execFileSync('cargo', ['build', '--release', '--bin', 'mrt-run'], {
    cwd: path.join(repoRoot, 'compiler'),
    stdio: ['ignore', 'ignore', 'inherit'],
  })

  const scratch = mkdtempSync(path.join(tmpdir(), 'mrt-rust-'))
  let checked = 0
  let failures = 0
  const unsupported = new Set()

  function report(name, expected, actual) {
    if (NOT_IMPLEMENTED.test(actual)) {
      unsupported.add(name)
      console.log(`- ${name} (not compiled yet)`)
      return
    }
    checked++
    if (expected === actual) {
      console.log(`✓ ${name}`)
      return
    }
    failures++
    console.error(`\n✗ MISMATCH: ${name}`)
    console.error('  python:', JSON.stringify(expected))
    console.error('  vm:    ', JSON.stringify(actual))
  }

  function checkFile(name, file) {
    report(name, runPythonFile(file), runVmFile(file))
  }

  function checkSource(name, src) {
    const safe = name.replace(/[^a-z0-9]+/gi, '_').slice(0, 60)
    const file = path.join(scratch, `${safe}.mrt`)
    writeFileSync(file, src)
    checkFile(name, file)
  }

  function checkFiles(name, files) {
    const safe = name.replace(/[^a-z0-9]+/gi, '_').slice(0, 60)
    const root = path.join(scratch, `mod_${safe}`)
    for (const [relative, contents] of Object.entries(files)) {
      const full = path.join(root, relative)
      mkdirSync(path.dirname(full), { recursive: true })
      writeFileSync(full, contents)
    }
    checkFile(name, path.join(root, 'main.mrt'))
  }

  const examplesDir = path.join(repoRoot, 'examples')
  for (const file of readdirSync(examplesDir).sort()) {
    if (!file.endsWith('.mrt')) continue
    if (ENGINE_SPECIFIC_EXAMPLES.has(file)) continue
    checkFile(`example: ${file}`, path.join(examplesDir, file))
  }
  for (const { name, src } of REGRESSION_CASES) {
    checkSource(`regression: ${name}`, src)
  }
  for (const { name, files } of MODULE_CASES) {
    checkFiles(`modules: ${name}`, files)
  }

  console.log(`\n${checked - failures}/${checked} checks matched (${unsupported.size} not compiled by the VM yet).`)

  const appeared = [...unsupported].filter((n) => !UNSUPPORTED.has(n))
  const disappeared = [...UNSUPPORTED].filter((n) => !unsupported.has(n))
  if (appeared.length) {
    console.error(`\nThese cases newly fail to compile:\n  ${appeared.join('\n  ')}`)
  }
  if (disappeared.length) {
    console.error(
      `\nThese cases now run and should be removed from scripts/vm-unsupported.json:\n  ${disappeared.join('\n  ')}`,
    )
  }
  if (failures || appeared.length || disappeared.length) process.exit(1)
}

const __filename = fileURLToPath(import.meta.url)
main()
